"""Regenerate docs/tools.md and docs/examples/instagram-report.sample.json from the code.

Both come from the server running in-process against the fake API (a fictional account), so
they always match the tool definitions and the report's shape. Tests fail when they're stale.

Run from the repository root:  uv run python scripts/generate_docs.py
"""

from __future__ import annotations

import json
import sys
import tempfile
from pathlib import Path
from typing import Any

import anyio
from mcp import Client

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from tests.fakes import NOW, FakeInstagramAPI  # noqa: E402

from instagram_mcp import periods  # noqa: E402
from instagram_mcp.config import Settings  # noqa: E402
from instagram_mcp.server import build_server  # noqa: E402

TOOLS_DOC = ROOT / "docs" / "tools.md"
SAMPLE = ROOT / "docs" / "examples" / "instagram-report.sample.json"
GROUPS = [
    ("Account", ["get_instagram_auth_status", "get_instagram_profile"]),
    (
        "Analytics",
        [
            "get_instagram_performance_summary",
            "get_instagram_metrics_over_time",
            "get_instagram_audience",
            "get_instagram_online_followers",
        ],
    ),
    (
        "Posts, reels and stories",
        [
            "list_instagram_media",
            "get_instagram_media_insights",
            "get_instagram_top_media",
            "list_instagram_stories",
            "list_instagram_comments",
            "list_instagram_tagged_media",
        ],
    ),
    ("Other accounts", ["get_instagram_public_account"]),
    ("Reports and raw access", ["get_instagram_report", "query_instagram_api"]),
]


def _type(schema: dict[str, Any]) -> str:
    if "anyOf" in schema:
        parts = [_type(s) for s in schema["anyOf"] if s.get("type") != "null"]
        nullable = any(s.get("type") == "null" for s in schema["anyOf"])
        return " \\| ".join(parts) + (" \\| null" if nullable else "")
    if "enum" in schema:
        return " \\| ".join(f"`{v}`" for v in schema["enum"])
    if schema.get("type") == "array":
        return f"list[{_type(schema.get('items', {}))}]"
    if schema.get("type") == "object":
        return "object"
    return str(schema.get("type", "any"))


def _default(schema: dict[str, Any], required: bool) -> str:
    if required:
        return "**required**"
    return f"`{json.dumps(schema['default'], ensure_ascii=False)}`" if "default" in schema else ""


def _escape(text: str) -> str:
    return " ".join(text.split()).replace("|", "\\|")


def render_tools(tools: list[Any]) -> str:
    by_name = {tool.name: tool for tool in tools}
    documented = {name for _, names in GROUPS for name in names}
    missing = set(by_name) - documented
    if missing:
        raise SystemExit(f"Add these tools to GROUPS in scripts/generate_docs.py: {sorted(missing)}")
    lines = [
        "# Tool reference",
        "",
        "<!-- Generated by scripts/generate_docs.py from the tool definitions. Do not edit by hand. -->",
        "",
        "Every tool is read-only (annotated `readOnlyHint: true`, so clients can auto-approve it) and",
        "returns JSON. Dates are in the report timezone (`INSTAGRAM_MCP_TIMEZONE`, else the computer's);",
        "percentages are 0-100.",
        "",
    ]
    for group, names in GROUPS:
        lines += [f"## {group}", ""]
        for name in names:
            tool = by_name[name]
            lines += [f"### `{name}`", "", f"*{tool.title or name}*", ""]
            lines += [
                " ".join(line.strip() for line in (tool.description or "").splitlines() if line.strip()),
                "",
            ]
            properties = tool.input_schema.get("properties", {})
            required = set(tool.input_schema.get("required", []))
            if properties:
                lines += ["| Parameter | Type | Default | Description |", "|---|---|---|---|"]
                for param, schema in properties.items():
                    lines.append(
                        f"| `{param}` | {_type(schema)} | {_default(schema, param in required)} | "
                        f"{_escape(schema.get('description', ''))} |"
                    )
                lines.append("")
    return "\n".join(lines).rstrip() + "\n"


def render_sample(report: dict[str, Any]) -> str:
    return json.dumps(report, indent=2, ensure_ascii=False) + "\n"


async def collect() -> tuple[list[Any], dict[str, Any]]:
    original = periods.now
    periods.now = lambda tz: NOW.astimezone(tz)  # a fixed "today" for a stable sample
    try:
        with tempfile.TemporaryDirectory() as folder:
            settings = Settings(
                config_dir=Path(folder) / "config", output_dir=Path(folder) / "out", timezone="Europe/Paris"
            )
            async with Client(build_server(settings, api=FakeInstagramAPI())) as client:
                tools = list((await client.list_tools()).tools)
                result = await client.call_tool("get_instagram_report", {"include_thumbnails": True})
    finally:
        periods.now = original
    report = result.structured_content
    if not isinstance(report, dict):
        raise SystemExit("get_instagram_report returned no structured content")
    return tools, report


def main() -> None:
    tools, report = anyio.run(collect)
    TOOLS_DOC.write_text(render_tools(tools), encoding="utf-8")
    SAMPLE.parent.mkdir(parents=True, exist_ok=True)
    SAMPLE.write_text(render_sample(report), encoding="utf-8")
    print(f"Wrote {TOOLS_DOC.relative_to(ROOT)} and {SAMPLE.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
